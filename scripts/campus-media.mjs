    c.fillStyle='#dfedf7';
    for(let y=121;y<186;y+=28)for(let x=132;x<312;x+=36)c.fillRect(x,y,20,15);
    c.fillStyle='#5c4b3b'; c.fillRect(59,168,10,51); c.fillRect(398,167,9,51);
    disk.draw(63,155,31,'#2f8060'); disk.draw(402,153,33,'#2f8060');
